export const LEVEL_COUNT = RAW.length;

export function loadLevel(i) {
    const L = RAW[i], w = Math.max(...L.rows.map(r => r.length));
    const grid = L.rows.map(r => [...r.padEnd(w, '.')]);
    let spawn = { x: 24, y: 100 }, exit = null, checkpoints = [];
    grid.forEach((row, y) => row.forEach((c, x) => {
        if (c === 'S') { spawn = { x: x * TS + 3, y: y * TS }; row[x] = '.'; }
        if (c === 'E') { exit = { x: x * TS, y: y * TS }; row[x] = '.'; }
        if (c === 'C') { checkpoints.push({ x: x * TS, y: y * TS, id: checkpoints.length + 1 }); row[x] = '.'; }
    }));
    return { name: L.name, grid, w, h: grid.length, spawn, exit, checkpoints };
}
